USE tonkean;

CREATE TABLE users (
    id VARCHAR(40) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY users_email_uq (email)
);

CREATE TABLE data_sources (
    id VARCHAR(40) NOT NULL,
    type VARCHAR(20) NOT NULL,
    name VARCHAR(255) NOT NULL,
    config JSON NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id)
);

CREATE TABLE incoming_webhooks (
    id VARCHAR(40) NOT NULL,
    data_source_id VARCHAR(40) NOT NULL,
    token VARCHAR(64) NOT NULL,
    signing_secret VARCHAR(64) NOT NULL,
    external_id VARCHAR(512) NULL,
    status VARCHAR(32) NOT NULL,
    last_error TEXT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY incoming_webhooks_data_source_uq (data_source_id),
    CONSTRAINT incoming_webhooks_data_source_fk FOREIGN KEY (data_source_id) REFERENCES data_sources (id) ON DELETE CASCADE
);

CREATE TABLE incoming_webhook_payloads (
    id BIGINT NOT NULL AUTO_INCREMENT,
    incoming_webhook_id VARCHAR(40) NOT NULL,
    message_type VARCHAR(64) NOT NULL,
    raw_body MEDIUMTEXT NOT NULL,
    received_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY incoming_webhook_payloads_webhook_idx (incoming_webhook_id, received_at),
    CONSTRAINT incoming_webhook_payloads_webhook_fk FOREIGN KEY (incoming_webhook_id) REFERENCES incoming_webhooks (id) ON DELETE CASCADE
);

CREATE TABLE external_activities (
    id VARCHAR(40) NOT NULL,
    data_source_id VARCHAR(40) NOT NULL,
    type VARCHAR(40) NOT NULL,
    entity_key VARCHAR(1024) NOT NULL,
    payload JSON NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY external_activities_data_source_idx (data_source_id, created_at)
);

CREATE TABLE modules (
    id VARCHAR(40) NOT NULL,
    name VARCHAR(255) NOT NULL,
    is_published TINYINT(1) NOT NULL DEFAULT 0,
    created_by VARCHAR(40) NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id)
);

-- Node and edge ids are generated by the editor, so they are only unique within a module.
CREATE TABLE module_nodes (
    module_id VARCHAR(40) NOT NULL,
    id VARCHAR(64) NOT NULL,
    kind VARCHAR(20) NOT NULL,
    type VARCHAR(40) NOT NULL,
    label VARCHAR(255) NOT NULL,
    data_source_id VARCHAR(40) NULL,
    config JSON NOT NULL,
    position_x DOUBLE NOT NULL,
    position_y DOUBLE NOT NULL,
    PRIMARY KEY (module_id, id),
    KEY module_nodes_trigger_idx (kind, type, data_source_id),
    CONSTRAINT module_nodes_module_fk FOREIGN KEY (module_id) REFERENCES modules (id) ON DELETE CASCADE
);

CREATE TABLE module_edges (
    module_id VARCHAR(40) NOT NULL,
    id VARCHAR(64) NOT NULL,
    source_node_id VARCHAR(64) NOT NULL,
    target_node_id VARCHAR(64) NOT NULL,
    PRIMARY KEY (module_id, id),
    CONSTRAINT module_edges_module_fk FOREIGN KEY (module_id) REFERENCES modules (id) ON DELETE CASCADE
);

CREATE TABLE module_runs (
    id VARCHAR(40) NOT NULL,
    module_id VARCHAR(40) NOT NULL,
    external_activity_id VARCHAR(40) NULL,
    is_test TINYINT(1) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL,
    trigger_payload JSON NOT NULL,
    started_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    finished_at DATETIME(3) NULL,
    PRIMARY KEY (id),
    KEY module_runs_module_idx (module_id, started_at),
    CONSTRAINT module_runs_module_fk FOREIGN KEY (module_id) REFERENCES modules (id) ON DELETE CASCADE
);

CREATE TABLE module_run_steps (
    id BIGINT NOT NULL AUTO_INCREMENT,
    run_id VARCHAR(40) NOT NULL,
    node_id VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    output JSON NULL,
    error TEXT NULL,
    PRIMARY KEY (id),
    KEY module_run_steps_run_idx (run_id),
    CONSTRAINT module_run_steps_run_fk FOREIGN KEY (run_id) REFERENCES module_runs (id) ON DELETE CASCADE
);
